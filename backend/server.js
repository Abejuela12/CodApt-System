const JWT_SECRET = process.env.JWT_SECRET || 'codapt_dev_secret';
const JWT_EXPIRES_IN = '7d';

async function hashPassword(password) {
  return bcrypt.hash(password, 10);
}

async function verifyPassword(password, hash) {
  if (!hash) return false;

  const isBcrypt = hash.startsWith('$2a$') || hash.startsWith('$2b$') || hash.startsWith('$2y$');
  if (isBcrypt) {
    return bcrypt.compare(password, hash);
  }

  const legacyHash = crypto.createHash('sha256').update(password + 'codapt_salt').digest('hex');
  return legacyHash === hash;
}

function createAuthToken(user) {
  return jwt.sign(
    { id: user.id, email: user.email, role: user.role || 'student' },
    JWT_SECRET,
    { expiresIn: JWT_EXPIRES_IN }
  );
}

function sendSuccess(res, message, data = null) {
  const payload = { success: true, message, data };
  return res.json(payload);
}

function sendError(res, status, message, details = null) {
  const payload = { success: false, message, error: message, data: null };
  if (details) payload.details = details;
  return res.status(status).json(payload);
}

function verifyToken(req, res, next) {
  const authHeader = req.headers.authorization;
  const token = authHeader && authHeader.split(' ')[1];
  if (!token) return sendError(res, 401, 'Missing authorization token.');

  jwt.verify(token, JWT_SECRET, (err, decoded) => {
    if (err) return sendError(res, 401, 'Invalid or expired token.');
    req.user = decoded;
    next();
  });
}

function requireAdmin(req, res, next) {
  if (!req.user || req.user.role !== 'admin') {
    return sendError(res, 403, 'Admin access required.');
  }
  next();
}

/* ─────────────────────────────────────
   HELPER — map CART level → problem_tier
   CART outputs: 'Easy' | 'Intermediate' | 'Hard'
   problem_tier in DB: 'Beginner' | 'Intermediate' | 'Advanced'
───────────────────────────────────── */
function cartLevelToTier(cartLevel) {
  const map = {
    Easy:         'Beginner',
    Intermediate: 'Intermediate',
    Hard:         'Advanced',
  };
  return map[cartLevel] || 'Beginner';
}


function shouldDemote(
  profile,
  isCorrect,
  attempts,
  hintUsed,
  hasHardEvidence
) {
  if (hasHardEvidence) return false;

  const struggled =
    !isCorrect ||
    hintUsed ||
    attempts >= 3;

  const weakProfile =
    profile.success_rate < 0.50;

  return struggled && weakProfile;
}

function shouldDemoteToEasy(
  profile,
  attempts,
  structuralErrors
) {
  return (
    attempts >= 4 &&
    profile.success_rate < 0.40 &&
    structuralErrors > 1
  );
}


// ─── Load CART model at startup ───────────────────────────────────
// The model file is generated by running: node utils/trainCart.js
// Falls back gracefully if the file is missing (first-run scenario).
const CART_MODEL_PATH = path.join(__dirname, 'utils', 'cart_model.json');
const cartModel = new CARTClassifier();
let cartReady = false;

try {
  if (fs.existsSync(CART_MODEL_PATH)) {
    const exported = JSON.parse(fs.readFileSync(CART_MODEL_PATH, 'utf8'));
    cartModel.importTree(exported);
    cartReady = true;
    console.log(`✅ CART model loaded from ${CART_MODEL_PATH}`);
    console.log(`   Trained at : ${exported.meta.trained_at}`);
  } else {
    console.warn(`⚠ CART model not found at ${CART_MODEL_PATH}.`);
    console.warn(`  Run: node utils/trainCart.js   to generate it.`);
    console.warn(`  Falling back to heuristic rules until model is available.`);
  }
} catch (err) {
  console.error(`❌ Failed to load CART model: ${err.message}`);
  console.warn(`  Falling back to heuristic rules.`);
}


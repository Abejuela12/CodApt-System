/* ─────────────────────────────────────
   HELPER — SHA-256 password hash
───────────────────────────────────── */
function hashPassword(password) {
  return crypto.createHash('sha256').update(password + 'codapt_salt').digest('hex');
}

/* ─────────────────────────────────────
   HELPER — map CART level → problem_tier
   CART outputs: 'Easy' | 'Intermediate' | 'Hard'
   problem_tier in DB: 'Beginner' | 'Intermediate' | 'Advanced'
───────────────────────────────────── */
function cartLevelToTier(cartLevel) {
  const map = {
    Easy:         'Beginner',
    Intermediate: 'Intermediate',
    Hard:         'Advanced',
  };
  return map[cartLevel] || 'Beginner';
}


function shouldDemote(
  profile,
  isCorrect,
  attempts,
  hintUsed,
  hasHardEvidence
) {
  if (hasHardEvidence) return false;

  const struggled =
    !isCorrect ||
    hintUsed ||
    attempts >= 3;

  const weakProfile =
    profile.success_rate < 0.50;

  return struggled && weakProfile;
}

function shouldDemoteToEasy(
  profile,
  attempts,
  structuralErrors
) {
  return (
    attempts >= 4 &&
    profile.success_rate < 0.40 &&
    structuralErrors > 1
  );
}

/* ══════════════════════════════════════
   CODE EXECUTION — /api/run
══════════════════════════════════════ */
app.post('/api/run', async (req, res) => {
  const { language, code } = req.body;
  if (!code || !language)
    return res.status(400).json({ output: 'No code or language provided.', error: true });

  const tmpDir = os.tmpdir();
  const lang   = language.toLowerCase();

  try {
    if (lang === 'python') {
      const filePath = path.join(tmpDir, `codapt_${Date.now()}.py`);
      fs.writeFileSync(filePath, code, 'utf8');
      runProcess(`python "${filePath}"`, filePath, res);

    } else if (lang === 'javascript') {
      const filePath = path.join(tmpDir, `codapt_${Date.now()}.js`);
      fs.writeFileSync(filePath, code, 'utf8');
      runProcess(`node "${filePath}"`, filePath, res);

    } else if (lang === 'java') {
      const wrapped  = wrapJava(code);
      const filePath = path.join(tmpDir, 'Main.java');
      fs.writeFileSync(filePath, wrapped, 'utf8');

      exec(`javac "${filePath}"`, { timeout: 10000 }, (compileErr, _, compileStderr) => {
        if (compileErr) {
          cleanup(filePath);
          return res.json({ output: compileStderr || 'Compilation error.', error: true });
        }
        const classPath = tmpDir;
        exec(`java -cp "${classPath}" Main`, { timeout: 10000 }, (runErr, stdout, stderr) => {
          cleanup(filePath);
          cleanup(path.join(tmpDir, 'Main.class'));
          if (runErr && !stdout)
            return res.json({ output: stderr || runErr.message, error: true });
          res.json({ output: stdout.trimEnd(), error: false });
        });
      });

    } else {
      res.status(400).json({ output: `Unsupported language: ${language}`, error: true });
    }
  } catch (err) {
    res.status(500).json({ output: err.message, error: true });
  }
});

function runProcess(command, filePath, res) {
  exec(command, { timeout: 10000 }, (err, stdout, stderr) => {
    cleanup(filePath);
    if (err && !stdout) return res.json({ output: stderr || err.message, error: true });
    res.json({ output: stdout.trimEnd(), error: !!stderr });
  });
}

function cleanup(filePath) {
  try { fs.unlinkSync(filePath); } catch (_) {}
}

function wrapJava(code) {
  if (/\bclass\s+\w+/.test(code))
    return code.replace(/public\s+class\s+\w+/, 'public class Main');
  return `public class Main {
    public static void main(String[] args) {
${code.split('\n').map(l => '        ' + l).join('\n')}
    }
}`;
}


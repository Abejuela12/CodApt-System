app.get('/api/recommendations/:userId', async (req, res) => {
  try {
    const { userId } = req.params;

    const [rows] = await db.query(
      `SELECT
         r.id,
         r.similarity_score,
         r.explanation,
         r.created_at,
         sp.title        AS source_title,
         sp.concept      AS source_concept,
         sp.difficulty   AS source_difficulty,
         sp.problem_tier AS source_tier,
         rp.id           AS rec_problem_id,
         rp.title        AS rec_title,
         rp.concept      AS rec_concept,
         rp.difficulty   AS rec_difficulty,
         rp.problem_tier AS rec_tier,
         rp.language     AS rec_language,
         rp.instruction  AS rec_instruction
       FROM recommendations r
       JOIN problems sp ON r.source_problem_id      = sp.id
       JOIN problems rp ON r.recommended_problem_id = rp.id
       WHERE r.user_id = ?
       ORDER BY r.created_at DESC
       LIMIT 10`,
      [userId]
    );

    res.json(rows);
  } catch (err) {
    console.error('❌ GET RECOMMENDATIONS:', err.message);
    res.status(500).json({ error: err.message });
  }
});


